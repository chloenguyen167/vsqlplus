create view v_Examination as
select
   `Examination`.`ID`,
   `Patient`.`SEX`,
   `Patient`.`Birthday`,
   `Patient`.`Description`,
   `Patient`.`First Date`,
   `Patient`.`Admission`,
   `Patient`.`Diagnosis` as `Patient_Diagnosis`,
   `Examination`.`Examination Date`,
   `Examination`.`aCL IgG`,
   `Examination`.`aCL IgM`,
   `Examination`.`ANA`,
   `Examination`.`ANA Pattern`,
   `Examination`.`aCL IgA`,
   `Examination`.`Diagnosis`,
   `Examination`.`KCT`,
   `Examination`.`RVVT`,
   `Examination`.`LAC`,
   `Examination`.`Symptoms`,
   `Examination`.`Thrombosis`
from
   `Examination`
left join `Patient` on `Examination`.`ID` = `Patient`.`ID`

